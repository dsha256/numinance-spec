// The control plane Connect API for the dashboard and the CLI (design section 20, "Connect API"). The control plane holds metadata only and the product works without it in sovereign mode. This file carries the part of section 20 that the control plane context implements: ChangeService (ListChanges, GetChange, Approve, Reject), FleetService (ListRunners, GetRunner, GetBreakerState) and LicenceService (GetLicence, Verify). BreakerService, RegistryService, KnowledgeService and the Escalate and GetEvidenceSummary verbs of ChangeService follow in later minors.
// Identity: no request carries a tenant or a principal. The server derives both from the verified credential of the call (WorkOS or the customer OIDC provider for a human, the runner credential for a runner) and scopes every read and write to that tenant, so a caller can never name another tenant's data. A change, a host or a bundle of another tenant is NOT_FOUND, exactly as one that does not exist.
// Mutations: Approve and Reject require a human principal. The server checks the decision against the author of the Change before it forwards it (the decider is not the author, and not in the author's run) and refuses with PERMISSION_DENIED otherwise. This is an early refusal: the runtime's verified-signal handler and policy decide again, and the control plane is never the authority for an approval.
// Licensing: expiry stops upgrades, new packs, the hosted dashboard and support. It never stops an installed runtime from completing authorised work, applying policy or exporting evidence, and there is no remote kill switch (ADR 0017). LicenceState reports it; it is not an instruction to any runtime.
// Untrusted text: titles and names come from the customer's own runtime and tickets, and are data. A client renders them as text, never as markup or instructions.
